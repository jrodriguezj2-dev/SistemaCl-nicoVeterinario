
PRAGMA foreign_keys = ON;

CREATE TABLE IF NOT EXISTS Propietarios (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    Codigo INTEGER NOT NULL UNIQUE,
    Nombre TEXT NOT NULL,
    Telefono TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS Veterinarios (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    Nombre TEXT NOT NULL,
    Telefono TEXT NOT NULL,
    Especialidad TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS Mascotas (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    Codigo INTEGER NOT NULL UNIQUE,
    Nombre TEXT NOT NULL,
    Especie TEXT NOT NULL,
    Raza TEXT NOT NULL,
    Edad INTEGER NOT NULL,
    PropietarioId INTEGER NOT NULL,
    FOREIGN KEY (PropietarioId) REFERENCES Propietarios(Id)
);

CREATE TABLE IF NOT EXISTS Citas (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    Numero INTEGER NOT NULL UNIQUE,
    MascotaId INTEGER NOT NULL,
    VeterinarioId INTEGER NOT NULL,
    Fecha TEXT NOT NULL,
    Motivo TEXT NOT NULL,
    Estado TEXT NOT NULL DEFAULT 'Pendiente',
    FOREIGN KEY (MascotaId) REFERENCES Mascotas(Id),
    FOREIGN KEY (VeterinarioId) REFERENCES Veterinarios(Id)
);

CREATE TABLE IF NOT EXISTS Expedientes (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    MascotaId INTEGER NOT NULL UNIQUE,
    Observaciones TEXT,
    FOREIGN KEY (MascotaId) REFERENCES Mascotas(Id)
);

CREATE TABLE IF NOT EXISTS Consultas (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    ExpedienteId INTEGER NOT NULL,
    Fecha TEXT NOT NULL,
    Descripcion TEXT NOT NULL,
    FOREIGN KEY (ExpedienteId) REFERENCES Expedientes(Id)
);

CREATE TABLE IF NOT EXISTS Diagnosticos (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    ConsultaId INTEGER NOT NULL,
    Descripcion TEXT NOT NULL,
    FOREIGN KEY (ConsultaId) REFERENCES Consultas(Id)
);

CREATE TABLE IF NOT EXISTS Tratamientos (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    ConsultaId INTEGER NOT NULL,
    Descripcion TEXT NOT NULL,
    FOREIGN KEY (ConsultaId) REFERENCES Consultas(Id)
);

CREATE TABLE IF NOT EXISTS Vacunas (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    MascotaId INTEGER NOT NULL,
    Nombre TEXT NOT NULL,
    Fecha TEXT NOT NULL,
    FOREIGN KEY (MascotaId) REFERENCES Mascotas(Id)
);

CREATE TABLE IF NOT EXISTS Pagos (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    CitaId INTEGER NOT NULL,
    Monto REAL NOT NULL,
    Fecha TEXT NOT NULL,
    Estado TEXT NOT NULL,
    FOREIGN KEY (CitaId) REFERENCES Citas(Id)
);
